import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
import {onRequestPost} from '../functions/api/events.js';
const script=readFileSync(new URL('../analytics-preferences.js',import.meta.url),'utf8');
const store=new Map();let cookie='';
const context={Object,location:{protocol:'https:',pathname:'/admin/content/'},localStorage:{getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)},document:{get cookie(){return cookie},set cookie(value){cookie=value.includes('Max-Age=0')?'':value.split(';')[0]}},window:{dispatchEvent(){}},CustomEvent:class{}};
vm.runInNewContext(script,context);
assert.equal(context.window.KZAnalyticsPrivacy.isExcluded(),true);
assert.equal(cookie,'kz_analytics_exclude=1');
context.location.pathname='/';vm.runInNewContext(script,context);assert.equal(context.window.KZAnalyticsPrivacy.isExcluded(),true);
context.window.KZAnalyticsPrivacy.setExcluded(false);assert.equal(cookie,'');assert.equal(context.window.KZAnalyticsPrivacy.isExcluded(),false);
context.location.pathname='/admin/';vm.runInNewContext(script,context);assert.equal(context.window.KZAnalyticsPrivacy.isExcluded(),false);
context.window.KZAnalyticsPrivacy.setExcluded(true);
const response=await onRequestPost({request:new Request('https://example.com/api/events',{method:'POST',headers:{Cookie:'other=1; kz_analytics_exclude=1'},body:'{}'}),env:{}});
assert.equal(response.status,202);assert.equal((await response.json()).excluded,true);
const visitor={...context,location:{protocol:'https:',pathname:'/'},localStorage:{getItem:()=>null},document:{cookie:''},window:{dispatchEvent(){}}};
vm.runInNewContext(script,visitor);assert.equal(visitor.window.KZAnalyticsPrivacy.isExcluded(),false);
console.log('Owner exclusion passed: default admin opt-out, cross-page persistence, explicit toggle, normal visitor unaffected, server skips storage.');
